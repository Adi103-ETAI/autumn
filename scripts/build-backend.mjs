// autumn — bundle the Electron main-process backend for production.
//
// WHY: the backend lives in TypeScript and is transpiled at RUNTIME by
// electron/ts-register.js, which needs the `typescript` package. `typescript`
// is a devDependency, so a packaged app (which ships only production
// dependencies) would crash on startup with "Cannot find module 'typescript'".
//
// The fix: bundle the backend to plain JavaScript at build time with esbuild.
// The bundle keeps the IPC layer EXTERNAL — electron/ipc/registry.js must stay
// a SINGLETON shared with electron/main.js, or the facade would dispatch into
// a different registry than the one the window talks to.
//
// The @/ alias (tsconfig paths) is resolved by esbuild's tsconfig support.

import { build } from "esbuild";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outfile = join(root, "electron", "dist", "backend.cjs");

if (!existsSync(join(root, "electron", "backend", "index.ts"))) {
  console.error("[build-backend] electron/backend/index.ts is missing");
  process.exit(1);
}

const result = await build({
  entryPoints: [join(root, "electron", "backend", "index.ts")],
  outfile,
  bundle: true,
  platform: "node",
  target: "node20", // Electron 33 ships Node 20
  format: "cjs",
  sourcemap: false,
  minify: false,
  // The registry/facade must be a SINGLETON shared with electron/main.js.
  external: [
    "../ipc/registry",
    "../ipc/facade",
    "../ipc/envelope",
    "../ipc/ipcmain",
    "../ipc/manifest.json",
    "electron",
    // Native + heavy deps stay external: they are shipped as real modules.
    "@prisma/client",
    "node-pty",
    "prisma",
    "electron-updater",
    "ws",
    "remotion",
    "@remotion/cli",
    // The on-device STT runtime is OPTIONAL: it is not a dependency (it
    // would add ~30 MB to every installer), it is fetched on demand into the
    // user-data dir. The bundle keeps the require() and the runtime answers
    // "not available" when the module is absent.
    "sherpa-onnx-node",
  ],
  tsconfig: join(root, "tsconfig.json"),
  logLevel: "info",
  banner: {
    js: "// autumn — bundled Electron backend (generated by scripts/build-backend.mjs — do not edit)",
  },
});

if (result.errors.length) {
  console.error(`[build-backend] ${result.errors.length} error(s)`);
  process.exit(1);
}
console.log("[build-backend] wrote electron/dist/backend.cjs");
